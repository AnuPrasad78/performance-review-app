"""Migration chain tests against a real PostgreSQL — the release gate for
schema changes.

Every other backend test swaps repositories for stubs, so nothing else proves
that the schema can be built, upgraded, rolled back and re-upgraded. These do:

- build from nothing: an empty database reaches head (a new environment);
- no drift: the schema at head is exactly what the ORM models describe;
- stairway: every revision upgrades, downgrades and re-upgrades cleanly, so
  each release has a working rollback and its downgrade really reverses it;
- full round trip: head → base → head;
- data survives: a rollback below the latest revision keeps the review rows
  written at head.

They need a THROWAWAY database (the public schema is dropped and recreated)
named by PR_TEST_DATABASE_URL, and are skipped without it. CI provides a
postgres service container; locally:

    docker run -d --rm -p 55432:5432 -e POSTGRES_PASSWORD=test postgres:17
    PR_TEST_DATABASE_URL=postgresql+asyncpg://postgres:test@localhost:55432/postgres \
        pytest tests/test_migrations.py
"""

import asyncio
import os
from collections.abc import Iterator
from pathlib import Path

import pytest
from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from app.core.config import get_settings

TEST_DATABASE_URL = os.environ.get("PR_TEST_DATABASE_URL", "")
BACKEND_ROOT = Path(__file__).resolve().parent.parent

pytestmark = pytest.mark.skipif(
    TEST_DATABASE_URL == "",
    reason="PR_TEST_DATABASE_URL is not set (needs a throwaway PostgreSQL)",
)


def _execute(*statements: str) -> list[tuple[object, ...]]:
    async def run() -> list[tuple[object, ...]]:
        engine = create_async_engine(TEST_DATABASE_URL)
        rows: list[tuple[object, ...]] = []
        async with engine.begin() as connection:
            for statement in statements:
                result = await connection.execute(text(statement))
                if result.returns_rows:
                    rows = [tuple(row) for row in result]
        await engine.dispose()
        return rows

    return asyncio.run(run())


@pytest.fixture
def alembic_config(monkeypatch: pytest.MonkeyPatch) -> Iterator[Config]:
    # env.py reads the URL from Settings — the same path production uses.
    monkeypatch.setenv("PR_DATABASE_URL", TEST_DATABASE_URL)
    get_settings.cache_clear()
    _execute("DROP SCHEMA public CASCADE", "CREATE SCHEMA public")
    config = Config(str(BACKEND_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_ROOT / "alembic"))
    yield config
    # Leave the database migrated to head: the repository tests that share
    # PR_DATABASE_URL expect the release schema, whatever state a test left.
    _execute("DROP SCHEMA public CASCADE", "CREATE SCHEMA public")
    command.upgrade(config, "head")
    get_settings.cache_clear()


def _revisions_oldest_first(config: Config) -> list[str]:
    script = ScriptDirectory.from_config(config)
    return [revision.revision for revision in reversed(list(script.walk_revisions()))]


def _tables() -> set[str]:
    rows = _execute(
        "SELECT tablename FROM pg_tables WHERE schemaname = 'public'"
    )
    return {str(row[0]) for row in rows}


def test_chain_is_linear(alembic_config: Config) -> None:
    script = ScriptDirectory.from_config(alembic_config)
    assert len(script.get_heads()) == 1, "migration chain has branched — merge the heads"
    assert len(script.get_bases()) == 1


def test_empty_database_upgrades_to_head_without_drift(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")

    assert {"employees", "evaluations", "review_cycles", "alembic_version"} <= _tables()
    # Raises AutogenerateDiffsDetected when models and schema disagree.
    command.check(alembic_config)


def test_every_revision_upgrades_downgrades_and_reupgrades(alembic_config: Config) -> None:
    for revision in _revisions_oldest_first(alembic_config):
        command.upgrade(alembic_config, revision)
        command.downgrade(alembic_config, "-1")
        command.upgrade(alembic_config, revision)


def test_full_round_trip_from_head_to_base_and_back(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")

    assert _tables() == {"alembic_version"}

    command.upgrade(alembic_config, "head")
    command.check(alembic_config)


def test_rollback_of_latest_revision_keeps_review_data(alembic_config: Config) -> None:
    command.upgrade(alembic_config, "head")
    _execute(
        "INSERT INTO employees (employee_id, employee_name, email) "
        "VALUES ('EMP-1', 'Asha Menon', 'asha_menon@emids.com')",
        "INSERT INTO evaluations (employee_id, email, review_year, status, cycle_id, "
        "q1_employee_response) "
        "SELECT 'EMP-1', 'asha_menon@emids.com', 2026, 'SELF_EVALUATION_IN_PROGRESS', "
        "cycle_id, 'Shipped the intake rewrite' "
        "FROM review_cycles WHERE review_year = 2026",
    )

    command.downgrade(alembic_config, "-1")
    command.upgrade(alembic_config, "head")

    rows = _execute(
        "SELECT e.employee_id, v.q1_employee_response FROM employees e "
        "JOIN evaluations v ON v.employee_id = e.employee_id"
    )
    assert rows == [("EMP-1", "Shipped the intake rewrite")]


def test_readiness_follows_the_real_schema_revision(alembic_config: Config) -> None:
    from fastapi.testclient import TestClient

    from app.core.config import Settings
    from app.core.db import dispose_engine
    from app.main import create_app

    def probe() -> tuple[int, str]:
        asyncio.run(dispose_engine())
        with TestClient(create_app(Settings(database_url=TEST_DATABASE_URL))) as client:
            response = client.get("/api/ready")
        return response.status_code, response.json().get("code", "")

    assert probe() == (503, "schema_not_migrated")

    command.upgrade(alembic_config, "head")
    assert probe()[0] == 200

    command.downgrade(alembic_config, "-1")
    assert probe() == (503, "schema_behind")
